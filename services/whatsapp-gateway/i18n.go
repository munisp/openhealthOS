// tr renders key in the session language with English fallback.
func (ss *Session) tr(key string, args ...any) string {
	lang := ss.Lang
	if lang == "" {
		lang = "en"
	}
	msg, ok := msgs[lang][key]
	if !ok {
		msg = msgs["en"][key]
	}
	if len(args) > 0 {
		return fmt.Sprintf(msg, args...)
	}
	return msg
}
