package main

// Case management + CRM for emergency dispatch (ADR-0019).
//
// An incident is what happened at 14:32. A case is everything the
// system owes the caller afterwards: the ambulance actually arrived,
// someone checked within the hour, someone called back in two days.
// Emergencies are lost in the gap between "dispatched" and "actually
// cared for" — case management exists to close that gap with owners,
// tasks, due times, and outcomes. The CRM underneath remembers every
// contact as a person: who they are, how to reach them, what they
// consented to, and every interaction in order.
//
// Design rules:
//   - cases open automatically from triage (red/orange), never rely on
//     a human remembering paperwork mid-crisis;
//   - tasks are generated by the lifecycle, not typed by hand: arrival
//     check after dispatch, 48-hour welfare call after closure;
//   - every case has exactly one accountable owner at a time;
//   - outcomes are coded, not prose — a case ends resolved_care_received
//     or lost_to_followup, and the aggregate of outcomes is the
//     service's quality measure;
//   - follow-up contact requires consent (NDPA): the CRM records it,
//     the task rail respects it.

import (
	"fmt"
	"sort"
	"sync"
	"time"
)

// Case statuses.
const (
	CaseOpen       = "open"
	CaseInProgress = "in_progress"
	CaseFollowUp   = "follow_up"
	CaseResolved   = "resolved"
	CaseClosed     = "closed"
)

var caseTransitions = map[string][]string{
	CaseOpen:       {CaseInProgress, CaseClosed},
	CaseInProgress: {CaseFollowUp, CaseResolved, CaseClosed},
	CaseFollowUp:   {CaseResolved, CaseClosed},
	CaseResolved:   {CaseClosed},
}

// Outcome codes — the aggregate of these is the service's report card.
const (
	OutcomeCareReceived   = "resolved_care_received"
	OutcomeReferred       = "referred_onward"
	OutcomeSelfResolved   = "self_resolved"
	OutcomeFalseAlarm     = "false_alarm"
	OutcomeLostToFollowUp = "lost_to_followup"
	OutcomeDeceased       = "deceased"
)

// Task kinds.
const (
	TaskArrivalCheck = "arrival_check" // did help actually reach them?
	TaskCallback     = "callback"      // dispatcher-promised return call
	TaskFollowUp48h  = "followup_48h"  // post-closure welfare check
	TaskCustom       = "custom"
)

const (
	TaskOpen      = "open"
	TaskDone      = "done"
	TaskCancelled = "cancelled"
)

// SLA targets per triage band — how fast the system must confirm help
// arrived. Data, not vibes.
var arrivalSLA = map[string]time.Duration{
	TriageRed:    30 * time.Minute,
	TriageOrange: 4 * time.Hour,
	TriageGreen:  24 * time.Hour,
}

// Contact is the CRM anchor: one caller, however they reach us.
type Contact struct {
	Phone            string   `json:"phone"` // primary key of the CRM
	Name             string   `json:"name,omitempty"`
	PatientID        string   `json:"patient_id,omitempty"` // registry link when known
	Language         string   `json:"language,omitempty"`
	PreferredChannel string   `json:"preferred_channel,omitempty"` // whatsapp | sms | voice
	ConsentFollowUp  bool     `json:"consent_follow_up"`
	Tags             []string `json:"tags,omitempty"` // e.g. ["pregnant","frequent-caller"]
	Interactions     int      `json:"interactions"`
	FirstContactAt   string   `json:"first_contact_at"`
	LastContactAt    string   `json:"last_contact_at"`
}

// Interaction is one touch in the contact's history, in order.
type Interaction struct {
	ID         string `json:"id"`
	Phone      string `json:"phone"`
	Channel    string `json:"channel"`
	Direction  string `json:"direction"` // inbound | outbound
	Kind       string `json:"kind"`      // sos | callback | followup | note | status-update
	Summary    string `json:"summary"`
	IncidentID string `json:"incident_id,omitempty"`
	CaseID     string `json:"case_id,omitempty"`
	Actor      string `json:"actor"`
	TS         string `json:"ts"`
}

// Case is the managed episode of care around one contact.
type Case struct {
	ID           string          `json:"id"`
	ContactPhone string          `json:"contact_phone"`
	PatientID    string          `json:"patient_id,omitempty"`
	IncidentID   string          `json:"incident_id,omitempty"` // origin incident
	Title        string          `json:"title"`
	Priority     string          `json:"priority"` // mirrors triage: red | orange | green
	Status       string          `json:"status"`
	Owner        string          `json:"owner"` // one accountable case worker
	FacilityID   string          `json:"facility_id,omitempty"`
	Outcome      string          `json:"outcome,omitempty"`
	OpenedAt     string          `json:"opened_at"`
	UpdatedAt    string          `json:"updated_at"`
	ClosedAt     string          `json:"closed_at,omitempty"`
	Timeline     []TimelineEntry `json:"timeline"`
}

// CaseTask is one owed action with a due time.
type CaseTask struct {
	ID       string `json:"id"`
	CaseID   string `json:"case_id"`
	Kind     string `json:"kind"`
	DueAt    string `json:"due_at"`
	DoneAt   string `json:"done_at,omitempty"`
	Status   string `json:"status"`
	Assignee string `json:"assignee,omitempty"`
	Note     string `json:"note,omitempty"`
}

// ---------------------------------------------------------------- CRM store

// CaseStore extends the incident Store with the CRM + case plane.
type CaseStore interface {
	Store
	UpsertContactOnIntake(phone, channel, patientID, ts string) Contact
	PutContact(c Contact) error
	GetContact(phone string) (Contact, error)
	ListContacts(q string, limit int) []Contact
	AddInteraction(i Interaction) error
	Interactions(phone string) []Interaction
	PutCase(c Case) error
	GetCase(id string) (Case, error)
	ListCases(status, owner string) []Case
	OpenCaseFor(phone string) (Case, error)
	NextCaseID() string
	PutTask(t CaseTask) error
	ListTasks(caseID string) []CaseTask
	OpenTasks() []CaseTask
	NextTaskID() string
	NextInteractionID() string
}

type MemoryCaseStore struct {
	*MemoryStore
	mu2          sync.Mutex
	contacts     map[string]Contact
	interactions map[string][]Interaction
	cases        map[string]Case
	tasks        map[string]CaseTask
	caseSeq      int
	taskSeq      int
	interSeq     int
}

func NewMemoryCaseStore() *MemoryCaseStore {
	return &MemoryCaseStore{
		MemoryStore:  NewMemoryStore(),
		contacts:     map[string]Contact{},
		interactions: map[string][]Interaction{},
		cases:        map[string]Case{},
		tasks:        map[string]CaseTask{},
	}
}

func (m *MemoryCaseStore) UpsertContactOnIntake(phone, channel, patientID, ts string) Contact {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	c, ok := m.contacts[phone]
	if !ok {
		c = Contact{Phone: phone, FirstContactAt: ts, ConsentFollowUp: true} // SOS implies consent to be helped; revocable below
	}
	if patientID != "" {
		c.PatientID = patientID
	}
	c.PreferredChannel = channel
	c.LastContactAt = ts
	c.Interactions++
	m.contacts[phone] = c
	return c
}

func (m *MemoryCaseStore) PutContact(c Contact) error {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	m.contacts[c.Phone] = c
	return nil
}

func (m *MemoryCaseStore) GetContact(phone string) (Contact, error) {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	if c, ok := m.contacts[phone]; ok {
		return c, nil
	}
	return Contact{}, ErrNotFound
}

func (m *MemoryCaseStore) ListContacts(q string, limit int) []Contact {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	out := []Contact{}
	for _, c := range m.contacts {
		if q != "" && !containsFold(c.Name, q) && !containsFold(c.Phone, q) {
			continue
		}
		out = append(out, c)
	}
	sort.Slice(out, func(a, b int) bool { return out[a].LastContactAt > out[b].LastContactAt })
	if limit > 0 && len(out) > limit {
		out = out[:limit]
	}
	return out
}

func containsFold(s, sub string) bool {
	return len(sub) == 0 ||
		(len(s) >= len(sub) && indexFold(s, sub) >= 0)
}

func indexFold(s, sub string) int {
	ls, lsub := len(s), len(sub)
	for i := 0; i+lsub <= ls; i++ {
		match := true
		for j := 0; j < lsub; j++ {
			if lowerByte(s[i+j]) != lowerByte(sub[j]) {
				match = false
				break
			}
		}
		if match {
			return i
		}
	}
	return -1
}

func lowerByte(b byte) byte {
	if b >= 'A' && b <= 'Z' {
		return b + 32
	}
	return b
}

func (m *MemoryCaseStore) AddInteraction(i Interaction) error {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	m.interactions[i.Phone] = append(m.interactions[i.Phone], i)
	return nil
}

func (m *MemoryCaseStore) Interactions(phone string) []Interaction {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	src := m.interactions[phone]
	out := make([]Interaction, len(src))
	copy(out, src)
	return out
}

func (m *MemoryCaseStore) NextCaseID() string {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	m.caseSeq++
	return fmt.Sprintf("CASE-%05d", m.caseSeq)
}

func (m *MemoryCaseStore) NextTaskID() string {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	m.taskSeq++
	return fmt.Sprintf("TASK-%05d", m.taskSeq)
}

func (m *MemoryCaseStore) NextInteractionID() string {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	m.interSeq++
	return fmt.Sprintf("INT-%06d", m.interSeq)
}

func (m *MemoryCaseStore) PutCase(c Case) error {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	m.cases[c.ID] = c
	return nil
}

func (m *MemoryCaseStore) GetCase(id string) (Case, error) {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	if c, ok := m.cases[id]; ok {
		return c, nil
	}
	return Case{}, ErrNotFound
}

func (m *MemoryCaseStore) ListCases(status, owner string) []Case {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	out := []Case{}
	for _, c := range m.cases {
		if status != "" && c.Status != status {
			continue
		}
		if owner != "" && c.Owner != owner {
			continue
		}
		out = append(out, c)
	}
	sort.Slice(out, func(a, b int) bool { return out[a].OpenedAt < out[b].OpenedAt })
	return out
}

func (m *MemoryCaseStore) OpenCaseFor(phone string) (Case, error) {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	for _, c := range m.cases {
		if c.ContactPhone == phone && c.Status != CaseResolved && c.Status != CaseClosed {
			return c, nil
		}
	}
	return Case{}, ErrNotFound
}

func (m *MemoryCaseStore) PutTask(t CaseTask) error {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	m.tasks[t.ID] = t
	return nil
}

func (m *MemoryCaseStore) ListTasks(caseID string) []CaseTask {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	out := []CaseTask{}
	for _, t := range m.tasks {
		if t.CaseID == caseID {
			out = append(out, t)
		}
	}
	sort.Slice(out, func(a, b int) bool { return out[a].ID < out[b].ID })
	return out
}

func (m *MemoryCaseStore) OpenTasks() []CaseTask {
	m.mu2.Lock()
	defer m.mu2.Unlock()
	out := []CaseTask{}
	for _, t := range m.tasks {
		if t.Status == TaskOpen {
			out = append(out, t)
		}
	}
	sort.Slice(out, func(a, b int) bool { return out[a].DueAt < out[b].DueAt })
	return out
}
